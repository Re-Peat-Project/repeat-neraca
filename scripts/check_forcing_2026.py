#!/usr/bin/env python3
"""Earth Engine rain and evapotranspiration against the ERA5 forcing of the KHG deficit, dry season 2026 (method-plan.md, V2).

  python scripts/check_forcing_2026.py --khg-dir $REPEAT_KHG/16.02.01_sugihan_lumpur --khg-dir $REPEAT_KHG/14.02-04-05.01_kampar_gaung \
      --out docs/reports/forcing_2026_gee_vs_era5.md

Window 2026-06-01 to 2026-09-30 (CHIRPS on Earth Engine ends 2026-09-30). KHG means of the Earth Engine products are the
area-weighted means of the sub-KHG values (`03_neraca/inputs/balance_<product>_dekad.csv`, `units_landcover.csv`); ERA5 and the
WaPOR column of the deficit come from `03_neraca/inputs/forcing_daily.csv` (window `calibration`). Totals in mm.
"""
import argparse
from pathlib import Path

import pandas as pd

START, END = pd.Timestamp("2026-06-01"), pd.Timestamp("2026-10-01")     # end exclusive


def gee_total(inputs: Path, product: str, area: pd.Series) -> tuple[float, float]:
    d = pd.read_csv(inputs / f"balance_{product}_dekad.csv", dtype={"unit_id": str}, parse_dates=["start", "end"])
    d = d[(d.start >= START) & (d.end <= END)]
    cov = float((d.groupby("start")["time_cov"].first() * d.groupby("start")["days"].first()).sum() / (END - START).days)
    per_unit = d.groupby("unit_id")["mm"].sum(min_count=1)
    w = area.reindex(per_unit.index)
    return float((per_unit * w).sum() / w[per_unit.notna()].sum()), cov


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--khg-dir", action="append", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    L = ["# Dry-season 2026 rain and evapotranspiration: Earth Engine against ERA5", "",
         f"Window {START.date()} to {(END - pd.Timedelta(days=1)).date()}. Totals in mm, KHG mean. Generated by `scripts/check_forcing_2026.py`.", "",
         "| KHG | P CHIRPS | P ERA5 | ET WaPOR (GEE) | E WaPOR (deficit file) | E ERA5 | P - ET, CHIRPS - WaPOR | P - E, ERA5 | days covered: CHIRPS, WaPOR | days in the deficit file: ERA5, WaPOR |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for kd in map(Path, a.khg_dir):
        inp = kd / "03_neraca" / "inputs"
        area = pd.read_csv(inp / "units_landcover.csv", dtype={"unit_id": str}).set_index("unit_id")["area_km2"]
        p, pc = gee_total(inp, "chirps", area)
        e, ec = gee_total(inp, "wapor", area)
        f = pd.read_csv(inp / "forcing_daily.csv", parse_dates=["date"])
        f = f[(f.window == "calibration") & (f.date >= START) & (f.date < END)]
        pe, ee5 = f.P_era5_mm.sum(), f.E_era5_mm.sum()
        ew = f.E_wapor_mm.sum(min_count=1)
        L.append(f"| {kd.name} | {p:.0f} | {pe:.0f} | {e:.0f} | {'' if pd.isna(ew) else f'{ew:.0f}'} | {ee5:.0f} | {p - e:+.0f} | {pe - ee5:+.0f} | "
                 f"{pc:.2f}, {ec:.2f} | {f.P_era5_mm.notna().sum()}, {f.E_wapor_mm.notna().sum()} |")
    L += ["", "The deficit (`neraca_khg.csv`) uses ERA5 P - E as its central value; this table shows how far the Earth Engine pair would move it.", ""]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
