#!/usr/bin/env python3
"""Per sub-KHG deficit on the SiTMAT stations against the climatic balance of the same units (method-plan.md, V5).

  python scripts/check_unit_deficit.py --khg-dir $REPEAT_KHG/16.02.01_sugihan_lumpur --khg-dir $REPEAT_KHG/14.02-04-05.01_kampar_gaung \
      --out docs/reports/unit_deficit_v5.md

For each sub-KHG with at least --min-stations stations: the deficit of `deficit.py` (same Sy, edge days and station coverage rule),
with the unit's own stations and its own Earth Engine rain (CHIRPS) and evapotranspiration (WaPOR), 2026-06-01 to 2026-09-30
(CHIRPS ends 2026-09-30):

    deficit_u = max(0, -sum(P_u - ET_u) - Sy x dz_u x 10)

Question: does a unit with less water from the climate (lower u_wb_mean, more u_deficit_months, lower WB in the 2026 window) need
more supply? Spearman across the units with stations. One dry season and few stations per unit: read as a first look.
"""
import argparse
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from repeat_neraca import deficit as D
from repeat_neraca.balance import interception
from repeat_neraca.params import Registry

START, END = pd.Timestamp("2026-06-01"), pd.Timestamp("2026-10-01")     # end exclusive


def window_total(inputs: Path, product: str) -> pd.Series:
    d = pd.read_csv(inputs / f"balance_{product}_dekad.csv", dtype={"unit_id": str}, parse_dates=["start", "end"])
    d = d[(d.start >= START) & (d.end <= END) & (d.time_cov >= 0.999)]
    return d.groupby("unit_id")["mm"].sum(min_count=1)


def unit_rows(kd: Path, min_st: int, reg: Registry) -> pd.DataFrame:
    inp = kd / "03_neraca" / "inputs"
    units = gpd.read_file(kd / "02_delineation" / "subkhg_units.gpkg").to_crs(4326)
    st = pd.read_csv(inp / "stations.csv")
    pts = gpd.GeoDataFrame(st, geometry=gpd.points_from_xy(st.lon, st.lat), crs=4326)
    j = gpd.sjoin(pts, units[["unit_id", "geometry"]], predicate="within")
    daily = pd.read_csv(inp / "stations_daily.csv", parse_dates=["date"])
    obs = daily.pivot(index="date", columns="station_id", values="depth_cm").reindex(pd.date_range(START, END - pd.Timedelta(days=1)))
    P, E = window_total(inp, "chirps"), window_total(inp, "wapor")
    lc = pd.read_csv(inp / "units_landcover.csv", dtype={"unit_id": str})
    icpt = interception(lc, reg)
    c, sy, k = reg["runoff_coefficient"], D.DEFAULTS["sy"], D.DEFAULTS["edge_days"]
    bal = pd.read_csv(kd / "03_neraca" / "runs" / "balance" / "neraca_balance_unit.csv", dtype={"unit_id": str}).set_index("unit_id")
    rows = []
    for u, g in j.groupby("unit_id"):
        o = obs[[s for s in g.station_id if s in obs.columns]]
        o = o.loc[:, o.notna().mean() >= D.DEFAULTS["min_station_coverage"]]
        m = o.mean(axis=1).dropna()
        if o.shape[1] < min_st or len(m) < 2 * k:
            continue
        dz = float(m.iloc[-k:].mean() - m.iloc[:k].mean())
        net = float(P[u] - E[u])
        rows.append({"khg": kd.name, "unit_id": u, "n_stations": o.shape[1], "P_mm": P[u], "ET_mm": E[u], "dz_cm": dz,
                     "deficit_mm": D._deficit(net, dz, sy), "wb_2026_mm": P[u] * (1 - icpt.get(u, 0.0)) * (1 - c) - E[u],
                     "u_wb_mean": bal.loc[u, "u_wb_mean"], "u_deficit_months": bal.loc[u, "u_deficit_months"],
                     "balance_stable_ok": bal.loc[u, "balance_stable_ok"]})
    return pd.DataFrame(rows)


def rho(a, b):
    ok = np.isfinite(a) & np.isfinite(b)
    return (float(spearmanr(a[ok], b[ok]).correlation), int(ok.sum())) if ok.sum() >= 5 and np.std(a[ok]) > 0 and np.std(b[ok]) > 0 else (float("nan"), int(ok.sum()))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--khg-dir", action="append", required=True)
    ap.add_argument("--min-stations", type=int, default=3)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    reg = Registry.load()
    L = ["# Per sub-KHG deficit on stations against the climatic balance (V5)", "",
         f"Window {START.date()} to {(END - pd.Timedelta(days=1)).date()}; sub-KHG with at least {a.min_stations} SiTMAT stations "
         f"(each with readings on half the days). Deficit as `deficit.py` (Sy {D.DEFAULTS['sy']}), with the unit's own CHIRPS and WaPOR. "
         "Spearman across units; expected sign: negative for u_wb_mean and wb_2026, positive for u_deficit_months. Generated by `scripts/check_unit_deficit.py`.", ""]
    allr = []
    for kd in map(Path, a.khg_dir):
        r = unit_rows(kd, a.min_stations, reg)
        allr.append(r)
        if r.empty:
            L += [f"## {kd.name}", "", "No sub-KHG with enough stations.", ""]
            continue
        L += [f"## {kd.name}: {len(r)} sub-KHG with stations, flag balance_stable_ok = {int(r.balance_stable_ok.iloc[0])}", "",
              "| against deficit_mm | Spearman | units |", "|---|---|---|"]
        for col in ["u_wb_mean", "u_deficit_months", "wb_2026_mm"]:
            v, n = rho(r["deficit_mm"].values, r[col].values.astype(float))
            L.append(f"| {col} | {v:.2f} | {n} |")
        L += ["", f"Deficit across these units: {r.deficit_mm.min():.0f} to {r.deficit_mm.max():.0f} mm (median {r.deficit_mm.median():.0f}); "
              f"water table change {r.dz_cm.min():+.0f} to {r.dz_cm.max():+.0f} cm; stations per unit {r.n_stations.min()}-{r.n_stations.max()}.",
              f"The deficit uses the same P and ET as the balance. Across units the climatic part -(P - ET) spans "
              f"{(r.ET_mm - r.P_mm).max() - (r.ET_mm - r.P_mm).min():.0f} mm and the station part Sy x dz x 10 spans "
              f"{D.DEFAULTS['sy'] * 10 * (r.dz_cm.max() - r.dz_cm.min()):.0f} mm, so where the station part is small the Spearman with wb_2026 "
              "is close to mechanical; the one with u_wb_mean (2018-2025) carries more information.", ""]
    pd.concat(allr).to_csv(Path(a.out).with_suffix(".csv"), index=False, float_format="%.2f")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
