"""MOD16A2GF (gap-filled) against MOD16A2 (not gap-filled) over the dekads where both exist.

    python scripts/check_mod16_nrt.py [--khg <code> ...] [--out docs/reports/mod16_gf_vs_nrt.md]

Reads `<REPEAT_KHG>/<khg>/03_neraca/inputs/model/balance_mod16_dekad.csv` and `balance_mod16nrt_dekad.csv` (whole-KHG
dekad totals from repeat_common.fetch_gee_balance). Only dekads with a value in both files count. The 2026 balance uses
the version without gap filling, so this gives the size of the step between the two versions.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parents[1]


def one(folder: Path) -> dict | None:
    d = folder / "03_neraca" / "inputs" / "model"
    gf, nrt = d / "balance_mod16_dekad.csv", d / "balance_mod16nrt_dekad.csv"
    if not (gf.exists() and nrt.exists()):
        return None
    a = pd.read_csv(gf, parse_dates=["start"]).set_index("start")["mm"].rename("gf")
    b = pd.read_csv(nrt, parse_dates=["start"]).set_index("start")["mm"].rename("nrt")
    j = pd.concat([a, b], axis=1).dropna()
    if j.empty:
        return None
    return {"khg": folder.name, "dekads": len(j), "from": j.index.min().date(), "to": j.index.max().date(),
            "gf_mm_yr": j.gf.sum() / len(j) * 36.5, "nrt_mm_yr": j.nrt.sum() / len(j) * 36.5,
            "nrt_vs_gf_pct": 100 * (j.nrt.sum() / j.gf.sum() - 1), "r": j.gf.corr(j.nrt)}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--khg", nargs="*", help="KHG folder names or prefixes (default: every folder under REPEAT_KHG)")
    ap.add_argument("--out", default=str(HERE / "docs" / "reports" / "mod16_gf_vs_nrt.md"))
    a = ap.parse_args(argv)
    root = Path(os.environ["REPEAT_KHG"])
    folders = sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith(("_", ".")))
    if a.khg:
        folders = [p for p in folders if any(p.name.startswith(k) for k in a.khg)]
    rows = [r for r in map(one, folders) if r]
    df = pd.DataFrame(rows)
    lines = ["# MOD16A2GF against MOD16A2 over the dekads where both exist", "",
             "Whole-KHG dekad totals, mm. `nrt_vs_gf_pct` = (sum of MOD16A2 / sum of MOD16A2GF - 1) x 100 over the shared dekads; "
             "annual values are the mean dekad total x 36.5. Generated by `scripts/check_mod16_nrt.py`.", "",
             "| KHG | shared dekads | first | last | GF (mm/yr) | not gap-filled (mm/yr) | difference (%) | r |",
             "|---|---|---|---|---|---|---|---|"]
    for r in df.itertuples():
        lines.append(f"| {r.khg} | {r.dekads} | {r._3} | {r.to} | {r.gf_mm_yr:.0f} | {r.nrt_mm_yr:.0f} | {r.nrt_vs_gf_pct:+.1f} | {r.r:.2f} |")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
