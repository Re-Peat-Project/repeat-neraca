#!/usr/bin/env python3
"""Reproduce the 2021 Kahayan-Sebangau neraca air (research_notes/gee_2021_kahayan_sebangau.md) from the fetched TerraClimate tables.

  python -m repeat_common.fetch_gee_balance --units users/akramsp/BatasSubKHG_KahayanSebangau --id-field SubKHG \
      --products terraclimate_pr,terraclimate_aet --step month --start 2010-01-01 --end 2021-01-01 --no-landcover --out <inputs>
  python scripts/reproduce_2021.py --inputs $REPEAT_KHG/62.11-14.02_kahayan_sebangau/03_neraca/inputs/units_2021 --out docs/reports/kahayan_sebangau_2021_reproduction.md

The 2021 balance is `WB = pr - aet/10 - C pr` with C = 0.25 (all scripts) or C = 0.35 for sub-KHG 1, 2, 4, 8, 11-16 (Akram_NeracaAir_2).
Check: the same expression evaluated directly on Earth Engine and reduced per sub-KHG at 2,500 m, the scale of the 2021 charts,
for two months, against the tables (reduced on TerraClimate's own 4,638 m grid). Run with the root .venv (earthengine-api).
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

C35 = {1, 2, 4, 8, 11, 12, 13, 14, 15, 16}


def table(inputs: Path, product: str) -> pd.DataFrame:
    d = pd.read_csv(inputs / f"balance_{product}_month.csv", parse_dates=["start"])
    return d.pivot(index="start", columns="unit_id", values="mm")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--inputs", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--no-check", action="store_true", help="skip the direct Earth Engine check")
    a = ap.parse_args()
    inp = Path(a.inputs)
    P, E = table(inp, "terraclimate_pr"), table(inp, "terraclimate_aet")      # E already x 0.1, mm
    units = sorted(P.columns, key=lambda u: int(u.split("_")[1]))
    c_split = pd.Series({u: 0.35 if int(u.split("_")[1]) in C35 else 0.25 for u in units})
    wb25 = P[units] - E[units] - 0.25 * P[units]
    wbsp = P[units] - E[units] - c_split * P[units]
    years = sorted(set(P.index.year))

    L = ["# Reproduction of the 2021 Kahayan-Sebangau neraca air", "",
         f"`WB = pr - aet/10 - C pr`, TerraClimate monthly, {years[0]}-{years[-1]}, the 16 sub-KHG of `users/akramsp/BatasSubKHG_KahayanSebangau`, "
         "reduced on TerraClimate's own grid (`repeat_common.fetch_gee_balance`). Generated by `scripts/reproduce_2021.py`.", ""]
    if not a.no_check:
        from repeat_common import fetch_gee_balance as B, gee
        ee = gee.init()
        fc = B._units_fc(ee, "users/akramsp/BatasSubKHG_KahayanSebangau", "SubKHG")
        L += ["## Check against the 2021 expression on Earth Engine", "",
              "| month | sub-KHG | WB from the tables (mm) | WB on Earth Engine at 2,500 m (mm) | difference |", "|---|---|---|---|---|"]
        for m in ["2015-09-01", "2019-08-01"]:
            img = ee.ImageCollection("IDAHO_EPSCOR/TERRACLIMATE").filterDate(m, pd.Timestamp(m) + pd.offsets.MonthEnd(1) + pd.Timedelta(days=1)).first()
            wb = img.expression("(p - (et/10) - (p*0.25))", {"p": img.select("pr"), "et": img.select("aet")})
            res = wb.reduceRegions(collection=fc, reducer=ee.Reducer.mean(), scale=2500).getInfo()
            for f in res["features"]:
                u, v = f["properties"]["unit_id"], f["properties"].get("mean")
                ours = wb25.loc[pd.Timestamp(m), u]
                if u in ("SubKHG_1", "SubKHG_6", "SubKHG_16"):
                    L.append(f"| {m[:7]} | {u} | {ours:.1f} | {v:.1f} | {ours - v:+.1f} |")
        L += ["", "Differences come from the reduction scale only (2,500 m in the 2021 charts against TerraClimate's 4,638 m grid here).", ""]
    L += ["## Per sub-KHG, C = 0.25 and the 0.25 / 0.35 split", "",
          "| sub-KHG | C (Akram_NeracaAir_2) | mean WB, C 0.25 (mm/month) | deficit months per year, C 0.25 | mean WB, split C | deficit months per year, split C |",
          "|---|---|---|---|---|---|"]
    for u in units:
        d25 = (wb25[u] < 0).groupby(wb25.index.year).sum().mean()
        dsp = (wbsp[u] < 0).groupby(wbsp.index.year).sum().mean()
        L.append(f"| {u} | {c_split[u]:.2f} | {wb25[u].mean():.1f} | {d25:.1f} | {wbsp[u].mean():.1f} | {dsp:.1f} |")
    k = wb25.mean(axis=1)
    clim = k.groupby(k.index.month).mean()
    share = (wb25 < 0).groupby(wb25.index.month).mean().mean(axis=1)
    L += ["", "## Calendar, KHG mean (C = 0.25)", "",
          "| | " + " | ".join(f"{m:02d}" for m in range(1, 13)) + " |", "|---" * 13 + "|",
          "| mean WB (mm) | " + " | ".join(f"{clim[m]:.0f}" for m in range(1, 13)) + " |",
          "| share of sub-KHG-months in deficit | " + " | ".join(f"{share[m]:.2f}" for m in range(1, 13)) + " |", ""]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
