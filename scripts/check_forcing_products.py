#!/usr/bin/env python3
"""Rain and evapotranspiration products against each other, to choose the forcing of the KHG deficit (decision 3 in method-plan.md).

  python scripts/check_forcing_products.py --khg-dir $REPEAT_KHG/16.02.01_sugihan_lumpur --khg-dir $REPEAT_KHG/14.02-04-05.01_kampar_gaung \
      --out docs/reports/forcing_products.md

No rain gauge is available (SiTMAT rain is empty; METAR has no amounts), so IMERG Final monthly, a merged satellite-gauge product,
is the reference for rain. Monthly KHG means (area weighted over the sub-KHG):
  - CHIRPS and IMERG, every month 2018-01 to 2025-09;
  - ERA5 (the deficit's forcing, `forcing_daily.csv`) against both, in the complete months of its windows before 2025-10;
  - ET: WaPOR, MOD16 and ERA5 evaporation in the same months.
Also whether CHIRPS and IMERG order the sub-KHG alike (Spearman of the 2018-2025 unit means).
Inputs: `03_neraca/inputs/balance_<product>_dekad.csv`, `balance_imerg_month.csv` (fetch_gee_balance --products imerg --step month),
`units_landcover.csv`, `forcing_daily.csv`.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

END = pd.Timestamp("2025-10-01")


def unit_months(inp: Path, product: str) -> pd.DataFrame:
    f = inp / f"balance_{product}_dekad.csv"
    d = pd.read_csv(f if f.exists() else inp / f"balance_{product}_month.csv", dtype={"unit_id": str}, parse_dates=["start"])
    d = d[(d.start >= "2018-01-01") & (d.start < END)]
    d["month"] = d.start.dt.to_period("M")
    d.loc[d.time_cov < 0.999, "mm"] = np.nan
    g = d.groupby(["month", "unit_id"])["mm"]
    return g.sum(min_count=1).where(g.count() == g.size()).unstack()


def khg_series(um: pd.DataFrame, area: pd.Series) -> pd.Series:
    w = area.reindex(um.columns)
    return (um * w).sum(axis=1, min_count=1) / um.notna().mul(w).sum(axis=1).replace(0, np.nan)


def stats(x: pd.Series, ref: pd.Series) -> str:
    ok = x.notna() & ref.notna()
    x, ref = x[ok], ref[ok]
    if len(x) < 3:
        return "n/a | n/a | 0"
    return f"{100 * (x.sum() - ref.sum()) / ref.sum():+.0f}% | {np.corrcoef(x, ref)[0, 1]:.2f} | {len(x)}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--khg-dir", action="append", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    L = ["# Forcing products compared (decision 3: forcing of the KHG deficit)", "",
         "Monthly KHG means, area weighted over the sub-KHG. Rain reference: IMERG Final monthly (merged satellite-gauge; no gauge "
         "is available in the workspace). Bias = (product total - reference total) / reference total over the months both have; "
         "r = Pearson correlation of the monthly totals. Generated by `scripts/check_forcing_products.py`.", ""]
    for kd in map(Path, a.khg_dir):
        inp = kd / "03_neraca" / "inputs"
        area = pd.read_csv(inp / "units_landcover.csv", dtype={"unit_id": str}).set_index("unit_id")["area_km2"]
        um = {p: unit_months(inp, p) for p in ["chirps", "imerg", "wapor", "mod16"]}
        k = {p: khg_series(v, area) for p, v in um.items()}
        f = pd.read_csv(inp / "forcing_daily.csv", parse_dates=["date"])
        f = f[f.date < END]
        f["month"] = f.date.dt.to_period("M")
        full = f.groupby("month").date.nunique() == f.groupby("month").date.first().dt.days_in_month
        e5 = f.groupby("month")[["P_era5_mm", "E_era5_mm"]].sum().loc[full[full].index]
        months = e5.index
        L += [f"## {kd.name}", "", "| comparison | months | bias | r | n |", "|---|---|---|---|---|",
              f"| rain: CHIRPS against IMERG | 2018-01 to 2025-09 | {stats(k['chirps'], k['imerg'])} |",
              f"| rain: CHIRPS against IMERG | ERA5 window months | {stats(k['chirps'].reindex(months), k['imerg'].reindex(months))} |",
              f"| rain: ERA5 against IMERG | ERA5 window months | {stats(e5['P_era5_mm'], k['imerg'].reindex(months))} |",
              f"| ET: WaPOR against MOD16 | 2018-01 to 2025-09 | {stats(k['wapor'], k['mod16'])} |",
              f"| ET: ERA5 evaporation against WaPOR | ERA5 window months | {stats(e5['E_era5_mm'], k['wapor'].reindex(months))} |",
              f"| ET: ERA5 evaporation against MOD16 | ERA5 window months | {stats(e5['E_era5_mm'], k['mod16'].reindex(months))} |", ""]
        mc, mi = um["chirps"].mean(), um["imerg"].mean()
        rho = spearmanr(mc, mi.reindex(mc.index)).correlation
        L += [f"ERA5 window months used: {', '.join(str(m) for m in months)}.",
              f"Sub-KHG order of mean monthly rain 2018-2025, CHIRPS against IMERG: Spearman {rho:.2f} ({len(mc)} units; "
              f"spread across units: CHIRPS {mc.min():.0f}-{mc.max():.0f}, IMERG {mi.min():.0f}-{mi.max():.0f} mm/month).", ""]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
