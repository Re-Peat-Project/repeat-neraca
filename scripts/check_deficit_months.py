#!/usr/bin/env python3
"""Calendar months in deficit from a balance run, against the months Amal (2022) reports for KHG Pulau Padang (method-plan.md, V3).

  python scripts/check_deficit_months.py --run $REPEAT_KHG/14.10.01_pulau_padang/03_neraca/runs/balance_khg_level \
      --out docs/reports/pulau_padang_deficit_months.md

Amal (2022, dissertation abstract, research_notes/runoff_coefficient_pulau_padang.md): deficit months January, February, March,
June, July; worst in February. Counts the complete years of the run (all 12 months present) for each ET source.
"""
import argparse
from pathlib import Path

import pandas as pd

AMAL = {1, 2, 3, 6, 7}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    m = pd.read_csv(Path(a.run) / "neraca_balance_monthly.csv")
    m["month"] = pd.PeriodIndex(m["month"], freq="M")
    L = ["# Deficit months, Pulau Padang: this balance against Amal (2022)", "",
         f"Run `{Path(a.run).name}`: KHG-mean `WB = P (1 - I) (1 - C) - ET`, CHIRPS rain. Share of complete years in which each calendar month "
         "has WB < 0. Amal (2022) months are marked *. Generated by `scripts/check_deficit_months.py`.", "",
         "| ET source | years | " + " | ".join(f"{k:02d}{'*' if k in AMAL else ''}" for k in range(1, 13)) + " |", "|---" * 14 + "|"]
    for et, g in m.groupby("et_source"):
        k = g.groupby("month")["WB_mm"].mean()                      # KHG mean (one unit here, or the mean of units)
        yrs = [y for y in sorted(set(k.index.year)) if k[k.index.year == y].notna().sum() == 12]
        k = k[k.index.year.isin(yrs)]
        share = (k < 0).groupby(k.index.month).mean()
        L.append(f"| {et} | {yrs[0]}-{yrs[-1]} ({len(yrs)}) | " + " | ".join(f"{share.get(i, float('nan')):.2f}" for i in range(1, 13)) + " |")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
