#!/usr/bin/env python3
"""Design choices of the sub-KHG balance (decisions 1 and 2 in method-plan.md): rain per unit or KHG mean, central ET, threshold.

  python scripts/check_balance_design.py --inputs $REPEAT_KHG/16.02.01_sugihan_lumpur/03_neraca/inputs \
      --inputs $REPEAT_KHG/14.02-04-05.01_kampar_gaung/03_neraca/inputs \
      --inputs $REPEAT_KHG/62.11-14.02_kahayan_sebangau/03_neraca/inputs/units_2021 \
      --v5 docs/reports/unit_deficit_v5.csv --out docs/reports/balance_design.md

For each unit set and variant (rain: per unit or KHG mean; central ET: WaPOR or MOD16) runs `repeat_neraca.balance` into
`<inputs>/../runs/design_check/<variant>/` and reports: median and minimum year-to-year Spearman of the central source, Spearman
between the two ET sources, spread of u_wb_mean across units, Spearman of u_wb_mean with the forest share (WorldCover tree cover +
mangroves; the prioritisation's i_forest is the same kind of share), and, where the V5 table has the units, Spearman of u_wb_mean
with the per-unit deficit on stations (2026).

Threshold: the null distribution of the stability statistics when the order of units is random, by simulation (10,000 draws):
the 99th percentile of one Spearman between two sources, and of the median over the 28 pairs of 8 years, for each number of units.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from repeat_neraca import balance as B
from repeat_neraca.params import Registry


def null_quantiles(n: int, years: int = 8, draws: int = 10000, q: float = 0.99, seed: int = 0) -> tuple[float, float]:
    rng = np.random.default_rng(seed)
    one = np.empty(draws)
    med = np.empty(draws)
    iu = np.triu_indices(years, 1)
    for i in range(draws):
        r = np.argsort(rng.random((years, n)), axis=1).argsort(axis=1).astype(float)       # random ranks per year
        c = np.corrcoef(r)[iu]
        one[i], med[i] = c[0], np.median(c)
    return float(np.quantile(one, q)), float(np.quantile(med, q))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--inputs", action="append", required=True)
    ap.add_argument("--v5", default=None)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    reg = Registry.load()
    v5 = pd.read_csv(a.v5, dtype={"unit_id": str}) if a.v5 else None
    L = ["# Design of the sub-KHG balance: rain per unit or KHG mean, central ET, stability threshold", "",
         "Generated by `scripts/check_balance_design.py`. Rain CHIRPS; complete years 2018-2025. Spearman across units.", "",
         "| unit set | units | rain | central ET | years: median (min) | ET sources | std of u_wb_mean (mm/month) | with forest share | with station deficit 2026 (units) |",
         "|---|---|---|---|---|---|---|---|---|"]
    sizes = set()
    for inp in map(Path, a.inputs):
        name = next((p.parent.name for p in [inp, *inp.parents] if p.name == "03_neraca"), inp.name) + ("" if inp.name == "inputs" else f" ({inp.name})")
        lc = pd.read_csv(inp / "units_landcover.csv", dtype={"unit_id": str}).set_index("unit_id")
        forest = lc["wc_10"] + lc["wc_95"]
        root = next(p for p in [inp, *inp.parents] if p.name == "03_neraca")
        for rain_mode in ["unit", "khg"]:
            for central, other in [("wapor", "mod16"), ("mod16", "wapor")]:
                out = root / "runs" / "design_check" / f"{inp.name}_{rain_mode}_{central}"
                r = B.run(inp, out, "chirps", [central, other], reg, rain_mode)
                t = pd.read_csv(out / "neraca_balance_unit.csv", dtype={"unit_id": str}).set_index("unit_id")
                sizes.add(len(t))
                yrs = B.year_stability(pd.read_csv(out / "neraca_balance_monthly.csv", dtype={"unit_id": str})
                                       .query("et_source == @central").assign(month=lambda d: pd.PeriodIndex(d.month, freq="M"))
                                       .pivot(index="month", columns="unit_id", values="WB_mm"), r["years"])
                src = list(r["source_rho"].values())[0]
                fr = spearmanr(t["u_wb_mean"], forest.reindex(t.index)).correlation
                st = ""
                if v5 is not None:
                    m = v5.merge(t["u_wb_mean"].rename("wb").reset_index(), on="unit_id")
                    if len(m) >= 5:
                        st = f"{spearmanr(m['deficit_mm'], m['wb']).correlation:.2f} ({len(m)})"
                L.append(f"| {name} | {len(t)} | {rain_mode} | {central} | {np.nanmedian(yrs):.2f} ({np.nanmin(yrs):.2f}) | {src:.2f} | "
                         f"{t['u_wb_mean'].std(ddof=0):.1f} | {fr:.2f} | {st} |")
    L += ["", "## Null distribution of the stability statistics (random order of units)", "",
          "| units | 99th percentile, one Spearman (ET sources) | 99th percentile, median of 28 year pairs |", "|---|---|---|"]
    for n in sorted(sizes | {5, 10, 15, 20, 40}):
        o, m = null_quantiles(n)
        L.append(f"| {n} | {o:.2f} | {m:.2f} |")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
